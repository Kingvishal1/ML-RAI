#!/usr/bin/env python3
"""Learned gripper-target and wheel-velocity BC from V10 scripted demonstrations.

The supervised labels are still generated by V10. At inference this network
predicts all six finger targets and four wheel velocities for CLOSE/REVERSE.
The V10 approach models, virtual ball attachment, stop conditions, and safety
transitions remain unchanged. Not a physical force-closure grasp model.
"""
import argparse
from pathlib import Path
import numpy as np
import torch
from torch import nn

INPUT_DIM = 24
OUTPUT_DIM = 10
STAGES = {"closing": 0, "reverse": 1}


def features(ee_pos, ball_pos, finger_q, finger_qd, base_velocity_xy,
             base_bearing, reversed_m, close_elapsed, stage):
    """Same 24-feature observation in both recording and inference."""
    if stage not in STAGES:
        raise ValueError(f"Only closing/reverse can be learned: {stage}")
    stage_onehot = [1.0, 0.0, 0.0] if stage == "closing" else [0.0, 1.0, 0.0]
    obs = np.concatenate([
        np.asarray(ball_pos, dtype=np.float64)[:3] - np.asarray(ee_pos)[:3],
        np.asarray(finger_q, dtype=np.float64).reshape(6),
        np.asarray(finger_qd, dtype=np.float64).reshape(6),
        np.asarray(base_velocity_xy, dtype=np.float64).reshape(2),
        [np.cos(base_bearing), np.sin(base_bearing)],
        [np.clip(reversed_m, 0.0, 0.5)],
        [np.clip(close_elapsed, 0.0, 2.0)],
        stage_onehot,
    ]).astype(np.float32)
    if obs.shape != (INPUT_DIM,) or not np.isfinite(obs).all():
        raise ValueError("Invalid learned-controller observation")
    return obs


class Controller(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(INPUT_DIM, 128), nn.GELU(),
            nn.Linear(128, 128), nn.GELU(),
            nn.Linear(128, OUTPUT_DIM),
        )

    def forward(self, x):
        return self.net(x)


def load_controller(filename):
    try:
        ckpt = torch.load(filename, map_location="cpu", weights_only=True)
    except TypeError:  # torch<2.0
        ckpt = torch.load(filename, map_location="cpu")
    if ckpt.get("format") != "robotnik_grasp_reverse_bc_v1":
        raise ValueError("Wrong checkpoint type. Train using grasp_reverse_bc.py first.")
    model = Controller().eval()
    model.load_state_dict(ckpt["state_dict"])
    mx, sx = (np.asarray(ckpt[k], dtype=np.float32) for k in ("x_mean", "x_std"))
    my, sy = (np.asarray(ckpt[k], dtype=np.float32) for k in ("y_mean", "y_std"))
    if any(v.shape != shape for v, shape in ((mx, (INPUT_DIM,)), (sx, (INPUT_DIM,)),
                                              (my, (OUTPUT_DIM,)), (sy, (OUTPUT_DIM,)))):
        raise ValueError("Checkpoint has invalid normalization shapes")

    def predict(obs):
        with torch.inference_mode():
            out = model(torch.from_numpy((obs - mx) / sx).float().unsqueeze(0))
        return out.numpy().squeeze(0) * sy + my

    return predict


def train(paths, output, epochs=100, seed=42):
    torch.manual_seed(seed)
    np.random.seed(seed)
    xs, ys = [], []
    for path in paths:
        with np.load(path, allow_pickle=False) as data:
            x, y = data["obs"], data["action"]
        if (x.ndim != 2 or y.ndim != 2 or x.shape[1] != INPUT_DIM
                or y.shape[1] != OUTPUT_DIM or len(x) != len(y)
                or len(x) < 30 or not np.isfinite(x).all() or not np.isfinite(y).all()):
            raise ValueError(f"Bad/incomplete demonstration: {path}")
        print(f"Loaded {len(x)} frames from {path}")
        xs.append(x.astype(np.float32))
        ys.append(y.astype(np.float32))
    if len(xs) < 2:
        print("WARNING: only one demo; this policy will likely overfit one exact trajectory.")
    x = np.concatenate(xs)
    y = np.concatenate(ys)
    if not ((x[:, -3] == 1).any() and (x[:, -2] == 1).any()):
        raise ValueError("Need BOTH closing and reverse demonstration frames")
    print(f"Samples: {len(x)}, closing={int((x[:, -3] == 1).sum())}, "
          f"reverse={int((x[:, -2] == 1).sum())}")

    # Train/validation are frame-split; a different seed/ball position is
    # needed to honestly claim generalization.
    ids = np.random.permutation(len(x))
    cut = max(1, int(0.85 * len(x)))
    tr, va = ids[:cut], ids[cut:]
    if not len(va):
        raise ValueError("Too few frames")
    xm, xsdev = x[tr].mean(0), x[tr].std(0).clip(min=1e-3)
    ym, ysdev = y[tr].mean(0), y[tr].std(0).clip(min=1e-3)
    # Avoid adding artificial variance to constant outputs.
    x_tensor = torch.from_numpy(((x - xm) / xsdev).astype(np.float32))
    y_tensor = torch.from_numpy(((y - ym) / ysdev).astype(np.float32))
    net = Controller()
    opt = torch.optim.AdamW(net.parameters(), lr=6e-4, weight_decay=1e-5)
    best = float("inf")
    best_state = None
    batch = 256
    for epoch in range(1, epochs + 1):
        net.train()
        train_ids = np.random.permutation(tr)
        for sel in np.array_split(train_ids, max(1, int(np.ceil(len(tr) / batch)))):
            loss = torch.nn.functional.smooth_l1_loss(net(x_tensor[sel]), y_tensor[sel])
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
        net.eval()
        with torch.inference_mode():
            val = torch.nn.functional.smooth_l1_loss(net(x_tensor[va]), y_tensor[va]).item()
        if val < best:
            best = val
            best_state = {k: v.detach().cpu().clone() for k, v in net.state_dict().items()}
        if epoch == 1 or epoch % 10 == 0 or epoch == epochs:
            print(f"epoch={epoch:03d}/{epochs} validation_normalized_smoothL1={val:.6f}")
    net.load_state_dict(best_state)
    with torch.inference_mode():
        prediction = net(x_tensor[va]).numpy() * ysdev + ym
    print("Validation mean absolute error, finger joints (rad):",
          np.round(np.abs(prediction[:, :6] - y[va, :6]).mean(0), 4))
    print("Validation mean absolute error, wheel rates (rad/s):",
          np.round(np.abs(prediction[:, 6:] - y[va, 6:]).mean(0), 4))
    result = {"format": "robotnik_grasp_reverse_bc_v1", "state_dict": best_state,
              "x_mean": torch.from_numpy(xm), "x_std": torch.from_numpy(xsdev),
              "y_mean": torch.from_numpy(ym), "y_std": torch.from_numpy(ysdev),
              "samples": len(x), "source": [str(t) for t in paths]}
    output = Path(output)
    if output.exists():
        raise FileExistsError(f"Refusing to overwrite {output}")
    torch.save(result, output)
    print(f"Saved learned controller to {output}.")
    print("WARNING: The virtual ball constraint still exists in the simulation.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", nargs="+", required=True, help="Demonstration .npz files")
    parser.add_argument("--out", default="grasp_reverse_bc.pt")
    parser.add_argument("--epochs", type=int, default=100)
    args = parser.parse_args()
    train(args.data, args.out, epochs=args.epochs)


if __name__ == "__main__":
    main()
